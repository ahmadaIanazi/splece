test('local audio extraction prepares a complete offline request without network access',async t=>{
  const folder=await fs.mkdtemp(path.join(os.tmpdir(),'splece-audio-reference-'));
  t.after(()=>fs.rm(folder,{recursive:true,force:true}));
  const {p,d,take}=fixture();p.folder=folder;
  const file=path.join(folder,'source.mp4');
  await run(['-f','lavfi','-i','color=c=black:s=64x64:r=24:d=2','-f','lavfi','-i','sine=frequency=440:duration=2','-c:v','libx264','-pix_fmt','yuv420p','-c:a','aac','-shortest',file]);
  take.duration=2;p.clips[0].duration=1.25;p.clips[0].in=0.5;
  const media={...take,projectId:p.id,path:file};
  const store={media:id=>id===take.id?media:null};
  const snapshot={draft:d,capabilities:model,compiled:compilePrompt(p,d,model)};
  const service=createVideoService({data:folder,store,transport:async()=>{throw Error('Unexpected network request');},fetcher:async()=>{throw Error('Unexpected network request');}});
  await service.prepare(snapshot,p);
  assert.match(snapshot.requestPayload.reference_audio_urls[0],/^data:audio\/wav;base64,/);
  assert.equal(snapshot.requestPayload.prompt,snapshot.compiled.text);
  assert.equal(snapshot.soundReferenceBinding.takeId,take.id);
  assert.equal(snapshot.soundReferenceBinding.start,0.5);
  assert.equal(snapshot.soundReferenceBinding.duration,1.25);
  const sample=path.join(folder,snapshot.soundReferenceBinding.file);
  assert.equal((await probe(sample)).audio,true);
  await assert.rejects(prepareSoundReference({media:()=>({...media,projectId:'other'})},p,snapshot.compiled.soundReference),/missing from this project/);
  await assert.rejects(prepareSoundReference(store,p,{...snapshot.compiled.soundReference,duration:16}),/Invalid/);
  await assert.rejects(prepareSoundReference(store,p,{...snapshot.compiled.soundReference,start:9}),/past/);
  const silent=path.join(folder,'silent.mp4');await run(['-i',file,'-c:v','copy','-an',silent]);
  media.path=silent;
  await assert.rejects(service.prepare({...snapshot},p),/no audio stream/);
});
